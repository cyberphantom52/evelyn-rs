//! What a build needs beyond Evelyn itself, kept in Evelyn's data directory: the
//! pinned files it downloads the first time one is needed, each checked by its
//! SHA-256, and the key it signs APKs with, generated the first time.

mod pins;

use base64::prelude::{BASE64_STANDARD, Engine};
use pins::{Encoding, PINS, Pin};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{self, Read, Write},
    path::{Path, PathBuf},
    process::{Command, ExitStatus},
};
use thiserror::Error;

#[derive(Debug, Error)]
pub enum Error {
    #[error("no data directory for Evelyn on this system")]
    NoDataDir,
    #[error("Evelyn has no pinned {0}")]
    Unpinned(String),
    #[error("cannot download {url}: {source}")]
    Download {
        url: &'static str,
        #[source]
        source: Box<ureq::Error>,
    },
    #[error("{url} is not base64, as it is pinned to be")]
    Encoding { url: &'static str },
    #[error("{url} is not the pinned file: its SHA-256 is {found}")]
    Hash { url: &'static str, found: String },
    #[error("{0} is not the pinned file; delete it and run evelyn check")]
    Changed(PathBuf),
    #[error("cannot read {member} from {url}: {source}")]
    Archive {
        url: &'static str,
        member: &'static str,
        #[source]
        source: zip::result::ZipError,
    },
    #[error("cannot generate the signing key: {0}")]
    Key(String),
    #[error("{path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("cannot run {tool}: {source}")]
    Spawn {
        tool: String,
        #[source]
        source: io::Error,
    },
    #[error("{tool} failed ({status}):\n{output}")]
    Failed {
        tool: String,
        status: ExitStatus,
        output: String,
    },
}

fn io_at(path: &Path) -> impl FnOnce(io::Error) -> Error + '_ {
    move |source| Error::Io {
        path: path.to_path_buf(),
        source,
    }
}

fn key_error(error: impl std::fmt::Display) -> Error {
    Error::Key(error.to_string())
}

/// The key APKs are signed with: a PKCS#8 private key and its certificate.
pub struct Keys {
    pub key: PathBuf,
    pub certificate: PathBuf,
}

/// One thing `check` saw to, a pinned file or the signing key, and how it is.
pub struct Status {
    pub name: String,
    pub path: PathBuf,
    pub state: Result<State, Error>,
}

pub enum State {
    /// There already, and as pinned.
    Present,
    /// Fetched or generated by this check.
    New,
}

#[derive(Clone, Debug)]
pub struct Tools {
    root: PathBuf,
}

impl Tools {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    /// Evelyn's data directory: `~/Library/Application Support/evelyn` on macOS,
    /// `~/.local/share/evelyn` on Linux.
    pub fn user() -> Result<Self, Error> {
        Ok(Self::new(
            dirs::data_dir().ok_or(Error::NoDataDir)?.join("evelyn"),
        ))
    }

    /// A pinned Java tool, run with the host `java`.
    pub fn jar(&self, name: &str) -> Result<Command, Error> {
        let path = self.file(name)?;
        let mut command = Command::new("java");
        command.arg("-jar").arg(path);
        Ok(command)
    }

    /// Whether `name` is a file Evelyn has pinned, fetched or not.
    pub fn pinned(&self, name: &str) -> bool {
        pin(name).is_ok()
    }

    /// A pinned file, such as `apktool.jar`, downloaded if it is not yet.
    pub fn file(&self, name: &str) -> Result<PathBuf, Error> {
        let pin = pin(name)?;
        let path = self.root.join(pin.path);
        if !path.exists() {
            self.fetch(pin, &path)?;
        }
        Ok(path)
    }

    /// The signing key, generated if there is none yet.
    pub fn keys(&self) -> Result<Keys, Error> {
        let dir = self.root.join("keys");
        let keys = Keys {
            key: dir.join("evelyn.pk8"),
            certificate: dir.join("evelyn.x509.pem"),
        };
        if !keys.key.exists() || !keys.certificate.exists() {
            generate(&keys)?;
        }
        Ok(keys)
    }

    /// Fetch every pinned file Evelyn lacks and check those it has, and generate
    /// the signing key if there is none; each one's state, whether or not the
    /// others fail.
    pub fn check(&self) -> Vec<Status> {
        let mut statuses = Vec::new();
        for pin in &PINS {
            let path = self.root.join(pin.path);
            let state = match path.exists() {
                false => self.fetch(pin, &path).map(|()| State::New),
                true => match sha256(&path) {
                    Ok(found) if found == pin.file_sha256() => Ok(State::Present),
                    Ok(_) => Err(Error::Changed(path.clone())),
                    Err(error) => Err(error),
                },
            };
            statuses.push(Status {
                name: pin.path.to_owned(),
                path,
                state,
            });
        }
        let dir = self.root.join("keys");
        let present = dir.join("evelyn.pk8").exists() && dir.join("evelyn.x509.pem").exists();
        statuses.push(Status {
            name: "signing key".into(),
            path: dir,
            state: self.keys().map(|_| match present {
                true => State::Present,
                false => State::New,
            }),
        });
        statuses
    }

    /// Download `pin` to `path`, through a partial file beside it that becomes
    /// `path` only once it checks out.
    fn fetch(&self, pin: &Pin, path: &Path) -> Result<(), Error> {
        tracing::info!(url = pin.url, "downloading");
        let parent = path.parent().unwrap_or(&self.root);
        fs::create_dir_all(parent).map_err(io_at(parent))?;
        let partial = path.with_extension("part");
        let download = |to: &Path| -> Result<(), Error> {
            let response = ureq::get(pin.url)
                .call()
                .map_err(|source| Error::Download {
                    url: pin.url,
                    source: Box::new(source),
                })?;
            let mut body = response
                .into_body()
                .into_with_config()
                .limit(u64::MAX)
                .reader();
            let mut file = fs::File::create(to).map_err(io_at(to))?;
            let found = match pin.encoding {
                Encoding::Raw => copy_hashing(&mut body, &mut file, to)?,
                Encoding::Base64 => {
                    let mut encoded = Vec::new();
                    body.read_to_end(&mut encoded).map_err(io_at(to))?;
                    encoded.retain(|byte| !byte.is_ascii_whitespace());
                    let decoded = BASE64_STANDARD
                        .decode(&encoded)
                        .map_err(|_| Error::Encoding { url: pin.url })?;
                    copy_hashing(&mut decoded.as_slice(), &mut file, to)?
                }
            };
            if found != pin.sha256 {
                return Err(Error::Hash {
                    url: pin.url,
                    found,
                });
            }
            Ok(())
        };
        let fetched = match &pin.member {
            None => download(&partial),
            Some(member) => {
                let archive = path.with_extension("download");
                let extracted = download(&archive).and_then(|()| {
                    let at = |source| Error::Archive {
                        url: pin.url,
                        member: member.name,
                        source,
                    };
                    let file = fs::File::open(&archive).map_err(io_at(&archive))?;
                    let mut zip = zip::ZipArchive::new(file).map_err(at)?;
                    let mut entry = zip.by_name(member.name).map_err(at)?;
                    let mut out = fs::File::create(&partial).map_err(io_at(&partial))?;
                    let found = copy_hashing(&mut entry, &mut out, &partial)?;
                    if found != member.sha256 {
                        return Err(Error::Hash {
                            url: pin.url,
                            found,
                        });
                    }
                    Ok(())
                });
                let _ = fs::remove_file(&archive);
                extracted
            }
        };
        if let Err(error) = fetched {
            let _ = fs::remove_file(&partial);
            return Err(error);
        }
        fs::rename(&partial, path).map_err(io_at(path))
    }
}

fn pin(name: &str) -> Result<&'static Pin, Error> {
    PINS.iter()
        .find(|pin| pin.path == name)
        .ok_or_else(|| Error::Unpinned(name.to_owned()))
}

/// Copy `from` into `to`, returning the SHA-256 of what was copied, in hex.
fn copy_hashing(from: &mut impl Read, to: &mut impl Write, path: &Path) -> Result<String, Error> {
    let mut hasher = Sha256::new();
    let mut buffer = vec![0; 1 << 16];
    loop {
        let read = from.read(&mut buffer).map_err(io_at(path))?;
        if read == 0 {
            break;
        }
        hasher.update(&buffer[..read]);
        to.write_all(&buffer[..read]).map_err(io_at(path))?;
    }
    Ok(hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect())
}

fn sha256(path: &Path) -> Result<String, Error> {
    let mut file = fs::File::open(path).map_err(io_at(path))?;
    copy_hashing(&mut file, &mut io::sink(), path)
}

/// A new 2048-bit RSA key and a self-signed certificate for it.
fn generate(keys: &Keys) -> Result<(), Error> {
    use rsa::pkcs8::EncodePrivateKey;
    tracing::info!("generating the signing key");
    let key = rsa::RsaPrivateKey::new(&mut rand::rngs::OsRng, 2048).map_err(key_error)?;
    let der = key.to_pkcs8_der().map_err(key_error)?;
    let pair = rcgen::KeyPair::try_from(der.as_bytes()).map_err(key_error)?;
    let mut params = rcgen::CertificateParams::new(Vec::<String>::new()).map_err(key_error)?;
    params
        .distinguished_name
        .push(rcgen::DnType::CommonName, "Evelyn");
    let certificate = params.self_signed(&pair).map_err(key_error)?;
    let dir = keys.key.parent().unwrap_or(Path::new("."));
    fs::create_dir_all(dir).map_err(io_at(dir))?;
    write_private(&keys.key, der.as_bytes())?;
    fs::write(&keys.certificate, certificate.pem()).map_err(io_at(&keys.certificate))
}

/// Write `bytes` to a new file only its owner can read.
fn write_private(path: &Path, bytes: &[u8]) -> Result<(), Error> {
    let mut options = fs::OpenOptions::new();
    options.write(true).create(true).truncate(true);
    #[cfg(unix)]
    std::os::unix::fs::OpenOptionsExt::mode(&mut options, 0o600);
    options
        .open(path)
        .and_then(|mut file| file.write_all(bytes))
        .map_err(io_at(path))
}

/// Run to completion, returning stdout. Failures carry the combined output.
pub fn run(command: &mut Command) -> Result<Vec<u8>, Error> {
    let tool = command_name(command);
    tracing::debug!(command = ?command, "running");
    let output = command.output().map_err(|source| Error::Spawn {
        tool: tool.clone(),
        source,
    })?;
    if !output.status.success() {
        let mut text = String::from_utf8_lossy(&output.stdout).into_owned();
        text.push_str(&String::from_utf8_lossy(&output.stderr));
        return Err(Error::Failed {
            tool,
            status: output.status,
            output: text,
        });
    }
    Ok(output.stdout)
}

fn command_name(command: &Command) -> String {
    let program = command.get_program();
    let program = if program == "java" {
        command.get_args().nth(1).unwrap_or(program)
    } else {
        program
    };
    Path::new(program)
        .file_name()
        .unwrap_or(program)
        .to_string_lossy()
        .into_owned()
}

/// The regular files under `root`, as (path relative to `root`, full path), sorted.
/// Anything other than files and directories is an error.
pub fn files(root: &Path) -> io::Result<Vec<(String, PathBuf)>> {
    let mut found = Vec::new();
    let mut pending = vec![(String::new(), root.to_path_buf())];
    while let Some((prefix, dir)) = pending.pop() {
        for entry in std::fs::read_dir(&dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().into_owned();
            let relative = if prefix.is_empty() {
                name
            } else {
                format!("{prefix}/{name}")
            };
            let kind = entry.file_type()?;
            if kind.is_dir() {
                pending.push((relative, entry.path()));
            } else if kind.is_file() {
                found.push((relative, entry.path()));
            } else {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidInput,
                    format!(
                        "{} is neither a file nor a directory",
                        entry.path().display()
                    ),
                ));
            }
        }
    }
    found.sort();
    Ok(found)
}
